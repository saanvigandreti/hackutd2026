// Builds fixtures/dcgm-alerts.json from NVIDIA's published dcgm-exporter metric lists in fixtures/dcgm/.
// Each tag's etc/default-counters.csv becomes a TypeScript declaration snapshot: the metric names exported
// by default and the unit each row's help text states. Run: node scripts/generate-dcgm-contract.ts
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { MigrationBundle, Snapshot } from '../src/types.ts';

export const DCGM_REPOSITORY = 'https://github.com/NVIDIA/dcgm-exporter';
export const DCGM_TAGS = {
  before: { tag: '4.8.4', commit: 'fafd151148052628061a80450b4ee037a5fa0c3c', sha256: 'ddf9d12eb7c004a24241a84221843ce178c5ca075ffdf711e2d46046e7000006' },
  after: { tag: '4.9.0', commit: '4e663a526c4624ad0e18ad816f09b7be2c5348a7', sha256: '04a691a8cc2407a6ce3bf84c7e207a856b84627a1f21277e7a94aff6f0431d32' },
} as const;
export const csvUrl = (tag: string) => `https://raw.githubusercontent.com/NVIDIA/dcgm-exporter/${tag}/etc/default-counters.csv`;

/** Unit wording in the CSV help column, the brand type it maps to, and the constructor name. First match wins. */
const UNITS: [RegExp, string, string][] = [
  [/\(in C\)/, 'Celsius', 'celsius'],
  [/\(in W\)/, 'Watts', 'watts'],
  [/\(in MHz\)/, 'MHz', 'megahertz'],
  [/\(in mJ\)/, 'Millijoules', 'millijoules'],
  [/\(in %\)/, 'Percent', 'percent'],
  [/\(in MiB\)/, 'MiB', 'mebibytes'],
  [/\(in MB\/s\)/, 'MBPerSecond', 'megabytesPerSecond'],
  [/\(in ns\)/, 'Nanoseconds', 'nanoseconds'],
  [/in bytes per second/, 'BytesPerSecond', 'bytesPerSecond'],
  [/in bytes\b/, 'Bytes', 'bytes'],
  [/in hertz/, 'Hertz', 'hertz'],
  [/in joules/, 'Joules', 'joules'],
  [/in seconds/, 'Seconds', 'seconds'],
  [/as a ratio|^(?:the )?ratio of/i, 'Ratio', 'ratio'],
];

/** Brand type name for each unit string a Quantity carries (the constructor name). */
export const UNIT_BRANDS: Record<string, string> = Object.fromEntries(UNITS.map(([, brand, make]) => [make, brand]));

export interface CounterRow { name: string; type: string; help: string; unit: string | null }

/** Rows a tag exports by default: lines that are not comments. `unit` is the brand type name, or null when the help text states none. */
export function parseCounters(csv: string): CounterRow[] {
  return csv.split('\n').map((line) => line.trim()).filter((line) => line !== '' && !line.startsWith('#')).map((line) => {
    const [name = '', type = '', ...help] = line.split(',').map((part) => part.trim());
    const text = help.join(',').trim();
    return { name, type, help: text, unit: UNITS.find(([pattern]) => pattern.test(text))?.[1] ?? null };
  });
}

/** Unit brand of each metric (not label) that a tag exports by default. */
export function metricUnits(csv: string): Map<string, string | null> {
  return new Map(parseCounters(csv).filter((row) => row.type !== 'label').map((row) => [row.name, row.unit]));
}

const sha256 = (text: string) => createHash('sha256').update(text).digest('hex');
const quote = (text: string) => `'${text}'`;

export function generateContract(csv: string, side: keyof typeof DCGM_TAGS): string {
  const { tag, commit, sha256: expected } = DCGM_TAGS[side];
  if (sha256(csv) !== expected) throw new Error(`default-counters.csv for ${tag} does not match sha256 ${expected}`);
  const rows = parseCounters(csv);
  const metrics = rows.filter((row) => row.type !== 'label');
  const labels = rows.filter((row) => row.type === 'label');
  const units = UNITS.filter(([, brand]) => metrics.some((row) => row.unit === brand));
  return [
    `// Generated by Ketchup (scripts/generate-dcgm-contract.ts) from NVIDIA's published file`,
    `// ${csvUrl(tag)}`,
    `// dcgm-exporter tag ${tag}, commit ${commit}, file sha256 ${expected}.`,
    `// dcgm-exporter is licensed under Apache-2.0: ${DCGM_REPOSITORY}/blob/${tag}/LICENSE`,
    `// This is not an NVIDIA-published TypeScript API. It lists the metrics the exporter exports by default at`,
    `// this tag (the uncommented CSV rows) and the unit each row's help text states. Rows whose help text states`,
    `// no unit use plain numbers. The rule helpers at the end are Ketchup's own.`,
    '',
    `export type Quantity<U extends string> = number & { readonly __unit: U };`,
    ...units.map(([, brand, make]) => `export type ${brand} = Quantity<'${make}'>;\nexport declare function ${make}(value: number): ${brand};`),
    '',
    `/** Metrics exported by default at ${tag}. */`,
    `export type MetricName =\n${metrics.map((row) => `  | ${quote(row.name)}`).join('\n')};`,
    '',
    `/** Labels exported by default at ${tag}. */`,
    `export type LabelName = ${labels.map((row) => quote(row.name)).join(' | ') || 'never'};`,
    '',
    `/** Value type of each metric, from the unit stated in its CSV help text. */`,
    `export interface MetricUnits {`,
    ...metrics.map((row) => `  /** ${row.type}: ${row.help.replaceAll('*/', '* /')} */\n  ${quote(row.name)}: ${row.unit ?? 'number'};`),
    `}`,
    `export type UnitOf<M extends MetricName> = MetricUnits[M];`,
    '',
    `export type Duration = \`\${number}\${'s' | 'm' | 'h'}\`;`,
    `export type Severity = 'warning' | 'critical';`,
    `export interface AlertRule<M extends MetricName = MetricName> {`,
    `  name: string;`,
    `  metric: M;`,
    `  above?: UnitOf<M>;`,
    `  below?: UnitOf<M>;`,
    `  for?: Duration;`,
    `  severity: Severity;`,
    `  summary: string;`,
    `}`,
    `export declare function defineRule<M extends MetricName>(rule: AlertRule<M>): AlertRule<M>;`,
    '',
  ].join('\n');
}

const fixtures = new URL('../fixtures/', import.meta.url);
const read = (name: string) => readFileSync(new URL(name, fixtures), 'utf8');

export function buildBundle(): MigrationBundle {
  const snapshot = (side: keyof typeof DCGM_TAGS): Snapshot => ({
    version: DCGM_TAGS[side].tag, entry: 'index.d.ts',
    files: { 'index.d.ts': generateContract(read(`dcgm/default-counters-${DCGM_TAGS[side].tag}.csv`), side) },
  });
  return {
    format: 1,
    name: 'GPU health alerts',
    description: 'NVIDIA DCGM Exporter 4.9.0 renames its default GPU metrics and changes some units. These alert rules, written for Ketchup as an example, still name the 4.8.4 metrics, so after the upgrade they match nothing and never fire. The TypeScript contract for each version is generated by Ketchup from NVIDIA\'s published default-counters.csv.',
    intent: 'Keep every GPU health alert able to fire for on-call after the exporter upgrade, with the same configured limits converted to the units 4.9.0 reports.',
    dependency: {
      name: 'dcgm-exporter',
      source: { kind: 'published-contract', publisher: 'NVIDIA', url: DCGM_REPOSITORY },
      before: snapshot('before'),
      after: snapshot('after'),
    },
    sources: { 'src/gpu-alerts.ts': read('dcgm/gpu-alerts.ts.txt') },
  };
}

export const bundleText = () => `${JSON.stringify(buildBundle(), null, 2)}\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('dcgm-alerts.json', fixtures), bundleText());
  console.log('Wrote fixtures/dcgm-alerts.json');
}
