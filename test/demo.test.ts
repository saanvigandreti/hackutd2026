test('dropping the OpenTelemetry reader registration compiles but fails the scenario check', () => {
  const bundle = demoBundle('opentelemetry-metrics');
  const before = bundle.sources['src/metrics.ts'] ?? '';
  const head = "import { MeterProvider, type MetricReader } from '@opentelemetry/sdk-metrics';\n\n";
  const evidenceFor = (after: string) => {
    const report = checkPatch(bundle, [{ path: 'src/metrics.ts', before, after }]);
    return { report, evidence: demoEvidence(bundle, report, 'nemotron') };
  };
  for (const body of ['return new MeterProvider();', 'return new MeterProvider({ readers: [] });', 'new MeterProvider({ readers: [reader] });\n  return new MeterProvider();']) {
    const { report, evidence } = evidenceFor(`${head}export function createMetricsProvider(reader: MetricReader): MeterProvider {\n  ${body}\n}\n`);
    assert.deepEqual(report.diagnostics, [], `The compiler alone cannot see the lost registration: ${body}`);
    assert.equal(status(evidence, 'Repair compiles'), 'passed', body);
    assert.equal(status(evidence, 'The reader is still registered'), 'failed', body);
    assert.match(evidence?.checks.find((check) => check.name === 'The reader is still registered')?.detail ?? '', /does not list the reader it receives/);
    assert.equal(evidence?.candidateVerified, false);
  }
  const indirect = evidenceFor(`${head}export const createMetricsProvider = (reader: MetricReader): MeterProvider => {\n  const readers = [reader];\n  const provider = new MeterProvider({ readers });\n  return provider;\n};\n`);
  assert.equal(status(indirect.evidence, 'The reader is still registered'), 'passed', 'Registration through const variables is read, not pattern-matched.');
  for (const body of ['return new MeterProvider({ readers: false ? [reader] : [] });', 'return new MeterProvider({ readers: true ? [reader] : [] });', 'return new MeterProvider({ readers: [...(false ? [reader] : [])] });']) {
    const { evidence } = evidenceFor(`${head}export function createMetricsProvider(reader: MetricReader): MeterProvider {\n  ${body}\n}\n`);
    assert.equal(status(evidence, 'The reader is still registered'), 'failed', `A branch that drops the reader fails the check: ${body}`);
  }
  for (const body of ["return new MeterProvider({ 'readers': [reader] });", 'return new MeterProvider({ readers: [...[reader]] });', 'return new MeterProvider({ readers: Math.random() > 0.5 ? [reader] : [reader] });']) {
    assert.equal(status(evidenceFor(`${head}export function createMetricsProvider(reader: MetricReader): MeterProvider {\n  ${body}\n}\n`).evidence, 'The reader is still registered'), 'passed', body);
  }
  for (const body of ['let options = { readers: [reader] };\n  return new MeterProvider(options);', 'return (() => new MeterProvider())();']) {
    const { evidence } = evidenceFor(`${head}export function createMetricsProvider(reader: MetricReader): MeterProvider {\n  ${body}\n}\n`);
    assert.equal(status(evidence, 'The reader is still registered'), 'not-run', `A shape the check cannot follow is not reported as a lost registration: ${body}`);
    assert.match(evidence?.checks.find((check) => check.name === 'The reader is still registered')?.detail ?? '', /could not follow how createMetricsProvider builds/);
    assert.equal(evidence?.candidateVerified, false);
  }
});

test('metric rename pairs match the published lists and the operator rows', () => {
  const table = z.array(z.tuple([z.string(), z.string()])).parse(JSON.parse(fixture('dcgm/rename-pairs.json')));
  const bundle = demoBundle();
  const metrics = (text: string) => [...text.matchAll(/metric: '(DCGM_FI_\w+)'/g)].map((match) => match[1]);
  const pairs = metrics(original(bundle)).map((metric, index) => [metric, metrics(reference())[index]]);
  assert.deepEqual(table, pairs, 'The fixture lists every rule metric and its target name, in rule order.');
  const before = metricUnits(fixture('dcgm/default-counters-4.8.4.csv'));
  const after = metricUnits(fixture('dcgm/default-counters-4.9.0.csv'));
  for (const [old, renamed] of table) {
    assert.equal(before.has(old ?? '') && !after.has(old ?? ''), true, `${old} is a 4.8.4 default that 4.9.0 drops`);
    assert.equal(after.has(renamed ?? ''), true, `${renamed} is a 4.9.0 default`);
  }
  const evidence = demoEvidence(bundle, checkPatch(bundle, rehearsalProposal(bundle).edits));
  assert.deepEqual(evidence?.operator?.rows.map((row) => [row.original.match(/DCGM_FI_\w+/)?.[0], row.repaired.match(/DCGM_FI_\w+/)?.[0]]), table);
  assert.match(evidence?.operator?.headline ?? '', new RegExp(`${table.length} of ${table.length} alerts would never fire on 4\\.9\\.0`));
});

test('GPU findings on a renamed metric lead with the alert that stops firing', () => {
  const bundle = demoBundle();
  const findings = analyzeBundle(bundle).findings;
  const titled = findingHeadlines(bundle, findings);
  const power = titled.find((item) => item.detail.includes('DCGM_FI_DEV_POWER_USAGE'));
  assert.equal(power?.title, 'GpuBoardPowerHigh never fires: DCGM_FI_DEV_POWER_USAGE is renamed to DCGM_FI_DEV_BOARD_POWER_WATTS in 4.9.0');
  assert.match(power?.detail ?? '', /Type '"DCGM_FI_DEV_POWER_USAGE"' is not assignable to type 'MetricName'/, 'The compiler text stays as detail.');
  assert.equal(titled.filter((item) => / never fires: /.test(item.title)).length, 8);
  assert.deepEqual(titled.filter((item) => item.code === 2305), findings.filter((item) => item.code === 2305), 'Removed unit helpers keep the compiler title.');
  const otel = demoBundle('opentelemetry-metrics');
  const otelFindings = analyzeBundle(otel).findings;
  assert.deepEqual(findingHeadlines(otel, otelFindings), otelFindings);
});
