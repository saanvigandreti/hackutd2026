test('a rename-only repair is rejected because the units no longer match', () => {
  const bundle = demoBundle();
  const renames: [string, string][] = [['GPU_TEMP\'', 'GPU_TEMP_CELSIUS\''], ['MEMORY_TEMP\'', 'MEMORY_TEMP_CELSIUS\''], ['XID_ERRORS', 'XID_ERROR'],
    ['ROW_REMAP_FAILURE', 'ROW_REMAP_FAILED'], ['POWER_USAGE', 'BOARD_POWER_WATTS'], ['GPU_UTIL\'', 'GPU_UTIL_RATIO\''], ['FB_USED\'', 'FB_USED_BYTES\''], ['SM_CLOCK\'', 'SM_CLOCK_HERTZ\'']];
  const renamed = renames.reduce((text, [from, to]) => text.replace(`DCGM_FI_DEV_${from}`, `DCGM_FI_DEV_${to}`), original(bundle));
  const report = checkPatch(bundle, replace(bundle, renamed));
  assert.equal(report.accepted, false);
  assert.equal(report.diagnostics.some((item) => /'percent'|'mebibytes'|'megahertz'/.test(item.message)), true);
  const evidence = demoEvidence(bundle, report);
  assert.equal(status(evidence, 'Every rule watches'), 'passed', 'The names alone are right.');
  assert.equal(status(evidence, 'Threshold units match'), 'failed');
  assert.equal(status(evidence, 'Repair compiles'), 'failed');
  assert.equal(evidence?.candidateVerified, false);
});

