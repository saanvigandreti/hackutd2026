test('a threshold with the right unit type but an unconverted limit fails the unit check', () => {
  const bundle = demoBundle();
  const cases: [string, string, string, RegExp][] = [
    ['ratio(limits.idleUtilizationPercent / 100)', 'ratio(limits.idleUtilizationPercent)', 'GpuIdle', /converted from percent to a 0-1 ratio/],
    ['bytes(limits.framebufferUsedMiB * 1_048_576)', 'bytes(limits.framebufferUsedMiB)', 'GpuFramebufferHigh', /converted from MiB to bytes/],
    ['hertz(limits.smClockFloorHz)', 'hertz(limits.smClockFloorHz / 1_000_000)', 'GpuSmClockLow', /converted from megahertz to hertz/],
  ];
  for (const [from, to, rule, row] of cases) {
    const report = checkPatch(bundle, replace(bundle, reference().replace(from, to)));
    assert.equal(report.accepted, true, `The unit type alone cannot see the missing conversion: ${to}`);
    const evidence = demoEvidence(bundle, report, 'nemotron');
    assert.equal(status(evidence, 'Threshold units match'), 'failed', to);
    assert.match(evidence?.operator?.rows.find((item) => item.repaired.startsWith('Wrong scale'))?.repaired ?? '', row);
    assert.match(evidence?.operator?.nextAction ?? '', new RegExp(`does not convert the configured limit for ${rule};`));
    assert.doesNotMatch(evidence?.operator?.nextAction ?? '', /the repaired thresholds convert them/);
    assert.doesNotMatch(evidence?.operator?.headline ?? '', /^Same rules/);
    assert.equal(evidence?.candidateVerified, false);
  }
  const equivalent = reference().replace('* 1_048_576', '* 1024 * 1024').replace('limits.idleUtilizationPercent / 100', 'limits.idleUtilizationPercent * 0.01');
  assert.equal(status(demoEvidence(bundle, checkPatch(bundle, replace(bundle, equivalent))), 'Threshold units match'), 'passed', 'Equivalent arithmetic is read, not pattern-matched.');
  const unread = reference().replace('ratio(limits.idleUtilizationPercent / 100)', 'ratio(Math.min(limits.idleUtilizationPercent / 100, 1))');
  const evidence = demoEvidence(bundle, checkPatch(bundle, replace(bundle, unread)));
  assert.equal(status(evidence, 'Threshold units match'), 'not-run', 'Arithmetic Ketchup cannot read is reported as not checked, never as passed.');
  assert.match(evidence?.operator?.nextAction ?? '', /Check by hand that the thresholds of GpuIdle convert/);
  assert.equal(evidence?.candidateVerified, false);
});

